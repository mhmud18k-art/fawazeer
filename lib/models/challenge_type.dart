            'عند انتهاء الإجابات يضغط الحكم «اكتملت الإجابات» فيأخذ الفريق النقطة.',
          ],
        ChallengeType.auction => const [
            'الحكم يقرأ السؤال الذي له عدة إجابات صحيحة.',
            'تتزايد الفرق شفهيًا: كم إجابة يستطيع كل فريق أن يذكر.',
            'يضبط الحكم رقم المزايدة الفائزة بأزرار + و −.',
            'ثم يضغط على الفريق صاحب المزايدة، فيبدأ عدّاد ثلاثين ثانية فورًا. '
