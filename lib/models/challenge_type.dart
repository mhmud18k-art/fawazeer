            'الإجابة الصحيحة معلّمة بوضوح أمام الحكم وحده.',
            'تتشاور الفرق ثم يختار كل فريق خياره.',
            'يضغط الحكم على اسم الفريق الذي أصاب فيأخذ النقطة.',
            'إن لم يُصب أحد فلا نقطة، وننتقل للسؤال التالي.',
          ],
      };

  static ChallengeType? fromId(String id) {
    for (final t in ChallengeType.values) {
      if (t.id == id) return t;
    }
    return null;
  }
}
