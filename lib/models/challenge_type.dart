            'السترايكات تتراكم لكل فريق ولا تُصفَّر عند عودة دوره في السؤال نفسه.',
            'إذا بلغ فريق ثلاث سترايكات خسر النقطة، وتذهب النقطة لصاحب '
                'أقل سترايكات بين بقية الفرق (ويتقاسمها المتساوون في الأقل).',
            'ثم ننتقل لسؤال جديد تُصفَّر فيه السترايكات ويبدأ الدور من الفريق التالي.',
            'لكل فريق تمريرة (PASS) واحدة في التحدي كله: تنقل الدور للفريق '
