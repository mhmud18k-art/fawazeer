            'يضع الحكم الجهاز بين الفرق ويقرأ السؤال غيبًا.',
            'أول فريق يضغط زره تُضيء بطاقته وتخفت بطاقات الباقين، '
                'ولا تظهر الإجابة في هذه اللحظة إطلاقًا.',
            'حين يقرر الحكم، يضغط «إظهار السؤال» ليرى السؤال والإجابة.',
