///
/// الترتيب هنا هو ترتيب العرض فقط — ترتيب اللعب الفعلي يحدده اللاعب
/// في شاشة اختيار التحديات.
enum ChallengeType {
  dawr(
    id: 'dawr',
    title: 'الدور',
    tagline: 'إجابات متعددة، ثلاث سترايكات، وتمريرة واحدة',
  ),
  auction(
    id: 'auction',
    title: 'مين يزوّد',
    tagline: 'زايد على خصمك… ثم أثبت أنك تقدر',
  ),
  bell(
    id: 'bell',
    title: 'الجرس',
    tagline: 'أسرع إصبع يكسب حق الإجابة',
  ),
  whoAmI(
    id: 'who_am_i',
    title: 'من أنا',
    tagline: 'لغز بصيغة المتكلّم… خمّن من يكون',
  ),
  askJudge(
    id: 'ask_judge',
    title: 'اسأل الحكم',
    tagline: 'أوصاف متتابعة… من يلتقط الخيط أولًا',
  ),
  impossible(
    id: 'impossible',
    title: 'المستحيل',
    tagline: 'اختر الإجابة الصحيحة… إن استطعت',
  );

  const ChallengeType({
    required this.id,
    required this.title,
    required this.tagline,
  });

  /// المعرّف المستخدم في ملفات JSON والتخزين المحلي.
  final String id;

  /// اسم التحدي كما يظهر للمستخدم.
  final String title;

  /// وصف قصير يظهر تحت الاسم في البطاقات.
  final String tagline;

  /// هل السؤال من هذا النوع له إجابة واحدة محددة؟
  bool get hasSingleAnswer =>
      this == ChallengeType.bell ||
      this == ChallengeType.whoAmI ||
      this == ChallengeType.askJudge ||
      this == ChallengeType.impossible;

  /// هل يعرض السؤال خيارات جاهزة يختار منها اللاعبون؟
  bool get isMultipleChoice => this == ChallengeType.impossible;

  /// شرح قواعد التحدي — يظهر في نافذة «شرح».
